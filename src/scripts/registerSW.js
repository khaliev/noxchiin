// ============================================================================
// registerSW.js — регистрация Service Worker (офлайн-режим).
// ============================================================================
// Подключается как внешний модуль (не инлайн), чтобы Content-Security-Policy
// могла использовать строгий script-src 'self' без 'unsafe-inline'.
// ============================================================================

if ('serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch(() => {
      // SW недоступен (например, очень старый браузер) — просто работаем без офлайна.
    });
  });
}
