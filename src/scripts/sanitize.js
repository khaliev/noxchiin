// ============================================================================
// sanitize.js — санитизация пользовательского ввода (OWASP A05 — Injection).
// ============================================================================
// Всё, что вводит пользователь (например, имя профиля), ПЕРЕД сохранением
// и отображением пропускается через эти функции. Даже если где-то в будущем
// данные случайно попадут в innerHTML, HTML-теги уже будут вырезаны.
// ============================================================================

/** Максимальная длина имени игрока. */
export const MAX_NAME_LENGTH = 20;

/**
 * Очищает имя игрока: вырезает HTML-теги, убирает управляющие символы,
 * схлопывает пробелы и ограничивает длину.
 * @param {unknown} value — сырое значение (может быть не строкой).
 * @returns {string} Безопасная строка (может быть пустой).
 */
export function sanitizeName(value) {
  if (typeof value !== 'string') return '';
  return value
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f]/g, '') // управляющие символы
    .replace(/<[^>]*>/g, '') // вырезаем HTML-теги
    .replace(/\s+/g, ' ') // схлопываем повторяющиеся пробелы/переносы
    .trim()
    .slice(0, MAX_NAME_LENGTH);
}

/**
 * Проверяет, валидно ли имя (непустое и не слишком длинное) после очистки.
 * @param {unknown} value — значение.
 * @returns {boolean} true, если имя можно использовать.
 */
export function isValidName(value) {
  const cleaned = sanitizeName(value);
  return cleaned.length > 0;
}

/**
 * Экранирует строку для безопасной вставки в HTML-текст (на случай, если
 * где-то понадобится ручная вставка). Лучше использовать textContent —
 * эта функция как запасной вариант.
 * @param {unknown} value — значение.
 * @returns {string} Экранированная строка.
 */
export function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
